"""Generate ui/board_geometry.py from docs/mockups/build.py — the artboard's own numbers."""
import importlib.util, sys, re, pathlib

spec = importlib.util.spec_from_file_location("sheet", "docs/mockups/build.py")
sheet = importlib.util.module_from_spec(spec); sys.modules["sheet"] = sheet
spec.loader.exec_module(sheet)

BOARDS = {  # page key -> artboard fn
    "memory": "b09", "memory_one": "b10", "routines": "b11", "tools": "b12",
    "help": "b13", "security": "b14", "access": "b15", "plugins": "b16",
    "light": "b18", "consent": "b07",
}
REFLOW = {"gestures": "b19", "brand": "b21", "installer": "b22"}

def prims(fn):
    svg = fn()
    frame = re.search(r'viewBox="0 0 (\d+) (\d+)"', svg)
    rects, texts = [], []
    for m in re.finditer(r'<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)" rx="([\d.]+)"', svg):
        x, y, w, h, r = (float(v) for v in m.groups())
        rects.append((x, y, w, h, r))
    for m in re.finditer(r'<text x="([\d.]+)" y="([\d.]+)"[^>]*font-size="([\d.]+)"[^>]*>([^<]*)</text>', svg):
        x, y, s = float(m.group(1)), float(m.group(2)), float(m.group(3))
        texts.append((x, y, s, m.group(4)))
    toggles = [(float(a), float(b)) for a, b in re.findall(r'<circle cx="([\d.]+)" cy="([\d.]+)" r="7"', svg)]
    return (int(frame.group(1)), int(frame.group(2))), rects, texts, toggles

lines = ['"""Every board page\'s coordinates, extracted from the artboard that draws it.',
         '',
         'GENERATED by tools/gen_board_geometry.py from docs/mockups/build.py. Do not',
         'hand-edit: `tests/test_board_conformance.py` re-runs the extraction and fails',
         'if this file and the sheet disagree.',
         '',
         'WHY THE NUMBERS ARE HERE AT ALL. The first version of the thirteen board',
         'pages placed widgets from geometry invented at build time and referenced the',
         'artboards in prose. Nothing compared the two, and ten of the thirteen were',
         'wrong: board 9\'s list started 44 px high, board 15 had two language options',
         'where the sheet draws three, and every page drew its title twice because the',
         'panel already has one.',
         '',
         'WHAT IS IN HERE. Raw primitives, in drawing order, exactly as the sheet emits',
         'them: RECTS are (x, y, w, h, radius), TEXTS are (x, y, size, string), and the',
         'head is ALWAYS (62, 36) / (62, 54) because `panel_head()` draws the orb there.',
         '',
         'REFLOWED PAGES. b19/b21/b22 are 720-1280 px wide and cannot be transcribed',
         'into a 460 px panel; they are recorded with `reflow=True` and their own',
         'frame, and the conformance test exempts them from pixel equality while still',
         'requiring every widget to be inside the panel.',
         '"""',
         'from __future__ import annotations', '', 'BOARDS = {']

for key, fn in BOARDS.items():
    (w, h), rects, texts, toggles = prims(getattr(sheet, fn))
    lines.append(f'    "{key}": {{')
    lines.append(f'        "board": "{fn}", "frame": ({w}, {h}),')
    lines.append('        "rects": [')
    for r in rects:
        lines.append(f'            {tuple(int(v) if v == int(v) else v for v in r)},')
    lines.append('        ],')
    lines.append('        "texts": [')
    for t in texts:
        got = t[3].replace('"', '\\"')
        lines.append(f'            ({t[0]:g}, {t[1]:g}, {t[2]:g}, "{got}"),')
    lines.append('        ],')
    lines.append('    },')
lines.append('}')
lines.append('')
lines.append('# Artboards that are wider than the panel. `frame` is the sheet\'s; the page')
lines.append('# is a reflow and the conformance test checks bounds, not equality.')
lines.append('REFLOWED = {')
for key, fn in REFLOW.items():
    (w, h), _, _, _ = prims(getattr(sheet, fn))
    lines.append(f'    "{key}": ("{fn}", {w}, {h}),')
lines.append('}')
lines.append('')
lines.append('__all__ = ["BOARDS", "REFLOWED"]')
pathlib.Path("ui/board_geometry.py").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote ui/board_geometry.py", len(lines), "lines")
